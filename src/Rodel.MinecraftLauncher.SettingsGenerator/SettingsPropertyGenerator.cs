using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using System.Linq;
using System.Text;

namespace Rodel.MinecraftLauncher.SettingsGenerator;

/// <summary>Implements fixed-key settings properties without runtime reflection.</summary>
[Generator]
public sealed class SettingsPropertyGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor InvalidDeclaration = new(
        "RMLSET001", "Unsupported settings declaration",
        "'{0}' must be a public partial get/set primitive or enum property in a top-level, non-generic partial class",
        "Settings", DiagnosticSeverity.Error, true);

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var properties = context.SyntaxProvider.ForAttributeWithMetadataName(
            "Rodel.MinecraftLauncher.App.Settings.SettingPropertyAttribute",
            static (node, _) => node is PropertyDeclarationSyntax,
            static (ctx, _) => ctx);
        context.RegisterSourceOutput(properties, static (output, ctx) =>
        {
            var property = (IPropertySymbol)ctx.TargetSymbol;
            var syntax = (PropertyDeclarationSyntax)ctx.TargetNode;
            var owner = property.ContainingType;
            var isEnum = property.Type.TypeKind == TypeKind.Enum;
            var supported = isEnum || property.Type.SpecialType is SpecialType.System_Boolean or SpecialType.System_Int32
                or SpecialType.System_Int64 or SpecialType.System_Single or SpecialType.System_Double or SpecialType.System_String;
            if (!supported || property.IsStatic || property.DeclaredAccessibility != Accessibility.Public
                || !syntax.Modifiers.Any(SyntaxKind.PartialKeyword) || owner.ContainingType != null || owner.Arity != 0
                || owner.TypeKind != TypeKind.Class || property.GetMethod == null || property.SetMethod == null
                || property.SetMethod.IsInitOnly
                || !owner.DeclaringSyntaxReferences.Any(r => r.GetSyntax() is ClassDeclarationSyntax c && c.Modifiers.Any(SyntaxKind.PartialKeyword)))
            {
                output.ReportDiagnostic(Diagnostic.Create(InvalidDeclaration, syntax.GetLocation(), property.Name));
                return;
            }

            var argument = ctx.Attributes[0].ConstructorArguments[0];
            var defaultValue = argument.ToCSharpString();
            var get = isEnum ? "GetEnumSetting" : "GetSetting";
            var set = isEnum ? "SetEnumSetting" : "SetSetting";
            var type = property.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var name = "@" + property.Name;
            var ns = owner.ContainingNamespace.IsGlobalNamespace ? string.Empty : owner.ContainingNamespace.ToDisplayString();
            var source = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
            if (!owner.ContainingNamespace.IsGlobalNamespace) source.Append("namespace ").Append(ns).Append(";\n");
            source.Append("partial class @").Append(owner.Name).Append("\n{\n    public partial ").Append(type).Append(' ').Append(name)
                .Append("\n    {\n        get => ").Append(get).Append('<').Append(type).Append(">(").Append(defaultValue).Append(", nameof(").Append(name)
                .Append("));\n        set => ").Append(set).Append("(value, ").Append(defaultValue).Append(", nameof(").Append(name).Append("));\n    }\n}\n");
            output.AddSource(ns + "." + owner.Name + "." + property.Name + ".g.cs", source.ToString());
        });
    }
}